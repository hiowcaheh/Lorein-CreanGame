CREATE TABLE guilds (
    guild_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           text        NOT NULL,
    description    text        NOT NULL,
    chat           text        NOT NULL,
    leader_id      bigint      NOT NULL,
    honor          bigint      NOT NULL DEFAULT 100,
    silver         bigint      NOT NULL DEFAULT 1000,
    mushroom       bigint      NOT NULL DEFAULT 5000,
    fortress       smallint    NOT NULL DEFAULT 10,
    treasure       smallint    NOT NULL DEFAULT 0,
    instructor     smallint    NOT NULL DEFAULT 0,
    dung           smallint    NOT NULL DEFAULT 0,
    catapult       smallint    NOT NULL DEFAULT 3,
    portal_act     integer     NOT NULL DEFAULT 1,
    portal_monster integer     NOT NULL DEFAULT 1,
    portal_hp      bigint      NOT NULL DEFAULT 1003472384,
    portal_time    varchar(30) NOT NULL DEFAULT '0',
    coatofarms     varchar(50) DEFAULT '0D1306040E022802060A0B'
);

CREATE TABLE guild_chat (
    msg_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    donator_name text     NOT NULL,
    guild_id     bigint   NOT NULL,
    "time"       text     NOT NULL,
    type         integer  NOT NULL DEFAULT 0,
    sender_id    bigint   NOT NULL,
    reciver_id   bigint   NOT NULL,
    msg          text     NOT NULL,
    donate_value bigint   NOT NULL DEFAULT 0,
    donate_type  text     NOT NULL,
    donator_lvl  bigint   NOT NULL DEFAULT 0
);

CREATE INDEX idx_guild_chat_guild ON guild_chat (guild_id, msg_id DESC);

CREATE TABLE guild_invites (
    invite_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guild_id  integer NOT NULL,
    user_id   integer NOT NULL
);

CREATE TABLE guild_attacks (
    attack_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guild_id     bigint NOT NULL,
    target_id    bigint NOT NULL,
    initiater_id bigint NOT NULL,
    attack_time  bigint NOT NULL,
    fight        text   NOT NULL
);

CREATE TABLE guild_attacks_archive (
    attack_id          bigint NOT NULL PRIMARY KEY,
    guild_id           bigint NOT NULL,
    target_id          bigint NOT NULL,
    fight_data         text   NOT NULL,
    fight_data_reverse text   NOT NULL,
    success            text   NOT NULL
);

-- -------------------------------------------------- komunikacja i reszta --

CREATE TABLE messages (
    msg_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id  bigint   NOT NULL,
    reciver_id bigint   NOT NULL,
    "time"     bigint   NOT NULL,
    subject    text     NOT NULL,
    msg        text     NOT NULL,
    read       smallint NOT NULL DEFAULT 0
);

CREATE INDEX idx_messages_reciver ON messages (reciver_id, msg_id DESC);

CREATE TABLE chat (
    id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL,
    message text    NOT NULL,
    date    bigint  NOT NULL
);

CREATE INDEX idx_chat_date    ON chat (date);
CREATE INDEX idx_chat_user_id ON chat (user_id);

CREATE TABLE banned_ips (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ip varchar(45) NOT NULL,
    CONSTRAINT idx_ip_unique UNIQUE (ip)
);

CREATE TABLE vouchers (
    id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type   text         NOT NULL CHECK (type IN ('mushroom', 'silver')),
    amount integer      NOT NULL,
    used   integer      NOT NULL,
    code   varchar(255) NOT NULL
);

CREATE INDEX idx_vouchers_code ON vouchers (code);

CREATE TABLE witch (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    donation_type   smallint NOT NULL DEFAULT 1,
    item_amount     bigint   NOT NULL DEFAULT 0,
    item_max_amount bigint   NOT NULL DEFAULT 1000,
    work            smallint NOT NULL DEFAULT 0,
    scroll_1        integer  NOT NULL,
    scroll_2        integer  NOT NULL,
    scroll_3        integer  NOT NULL,
    scroll_4        integer  NOT NULL,
    scroll_5        integer  NOT NULL,
    scroll_6        integer  NOT NULL,
    scroll_7        integer  NOT NULL,
    scroll_8        integer  NOT NULL,
    scroll_9        integer  NOT NULL,
    scrolls         integer  NOT NULL DEFAULT 1,
    "time"          integer  NOT NULL DEFAULT 0
);

-- ---------------------------------------------------------- konfiguracja --

CREATE TABLE server_config (
    id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  varchar(300) NOT NULL,
    value varchar(300) NOT NULL,
