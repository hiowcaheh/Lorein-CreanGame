-- Schemat gry Lorein dla PostgreSQL / Supabase.
--
-- Konwersja z `sf555/DATABASE.sql` (MariaDB). Nazwy tabel i kolumn zostaly
-- zachowane co do znaku, zeby port kolejnych akcji z `req.php` byl
-- mechaniczny — kazde zapytanie z PHP ma tu swoj odpowiednik jeden do jednego.
--
-- UWAGA — trzy kolumny nosza nazwy zarezerwowane lub kolidujace w Postgresie
-- i w zapytaniach MUSZA byc w cudzyslowach:
--
--     user_data."group"      guild_chat."time"      witch."time"
--
-- Mapowanie typow:
--   int(11)          -> integer
--   bigint(20)       -> bigint
--   tinyint(4)       -> smallint      (wartosci 0/1 sa uzywane liczbowo,
--   tinyint(1)       -> smallint       wiec NIE zamieniamy ich na boolean)
--   tinytext/text    -> text
--   longtext         -> text
--   enum(...)        -> text + CHECK
--   AUTO_INCREMENT   -> GENERATED BY DEFAULT AS IDENTITY
--   datetime         -> timestamp

